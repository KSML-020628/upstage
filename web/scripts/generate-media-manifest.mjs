import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const publicRoot = path.join(root, "public", "images");
const outputPath = path.join(root, "app", "lib", "generated-media.ts");
const allowedExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".svg"]);

async function imageMap(directory, publicDirectory) {
  let entries = [];
  try {
    entries = await readdir(path.join(publicRoot, directory), { withFileTypes: true });
  } catch {
    return {};
  }

  return Object.fromEntries(entries
    .filter((entry) => entry.isFile() && allowedExtensions.has(path.extname(entry.name).toLowerCase()))
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((entry) => [
      path.basename(entry.name, path.extname(entry.name)),
      `/images/${publicDirectory}/${encodeURIComponent(entry.name)}`,
    ]));
}

const covers = await imageMap("university-covers", "university-covers");
const logos = await imageMap("university-logos", "university-logos");
const countries = await imageMap("country-covers", "country-covers");
const brand = await imageMap("brand", "brand");

const source = `// Generated by scripts/generate-media-manifest.mjs. Do not edit manually.\n` +
  `export const universityCoverImages: Record<string, string> = ${JSON.stringify(covers, null, 2)};\n\n` +
  `export const universityLogoImages: Record<string, string> = ${JSON.stringify(logos, null, 2)};\n\n` +
  `export const countryCoverImages: Record<string, string> = ${JSON.stringify(countries, null, 2)};\n\n` +
  `export const brandImages: Record<string, string> = ${JSON.stringify(brand, null, 2)};\n`;

await writeFile(outputPath, source, "utf8");
console.log(`Media manifest: ${Object.keys(covers).length} university covers, ${Object.keys(logos).length} logos, ${Object.keys(countries).length} country covers, ${Object.keys(brand).length} brand images`);
